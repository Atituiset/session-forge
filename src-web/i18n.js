function currentLang() {
  const saved = localStorage.getItem("sf.lang");
  if (saved && I18N_LOCALES[saved]) return saved;
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function t(key, vars) {
  const lang = currentLang();
  // English plural convention: a "<key>One" entry wins when n === 1.
  const k =
    lang === "en" && vars && Number(vars.n) === 1 && I18N_LOCALES.en[`${key}One`]
      ? `${key}One`
      : key;
  let s = I18N_LOCALES[lang]?.[k] ?? I18N_LOCALES.en[k] ?? key;
  if (vars) {
    for (const [k2, v] of Object.entries(vars)) {
      s = s.split(`{${k2}}`).join(String(v));
    }
  }
  return s;
}

function setLang(lang) {
  localStorage.setItem("sf.lang", lang);
  location.reload();
}

function applyI18nStatic() {
  document.documentElement.lang = currentLang();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.textContent = currentLang() === "zh-CN" ? "EN" : "中";
}

applyI18nStatic();
